#!/usr/bin/env python3
"""Generate portable JS/C constants from the canonical skill rules. Standard library only."""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

def outputs():
    references = ROOT.parent / 'skills/op1-design/references'
    spec = json.loads((references / 'design-kit.json').read_text())
    data = spec['tokens']
    js = '// Generated by tools/sync_tokens.py. Edit skills/op1-design/references/design-kit.json.\nexport const tokens = ' + json.dumps(data, indent=2) + ';\n'
    lines = ['/* Generated by tools/sync_tokens.py; MIT. No firmware or SDK dependency. */',
             '#ifndef SQUAREWAVE_OP1_UI_TOKENS_H', '#define SQUAREWAVE_OP1_UI_TOKENS_H',
             '/* Logical pixels; multiply by 1024 only in a Q10 geometry adapter. */']
    for key, value in data['coordinateSpace'].items():
        if isinstance(value, int): lines.append(f'#define OP1_UI_{key.upper()} {value}')
    lines.append(f'#define OP1_UI_CRITICAL_CONTENT_BOTTOM {data["safeArea"]["criticalContentBottom"]}')
    for key in ('left', 'top', 'right', 'bottom'):
        lines.append(f'#define OP1_UI_INSET_{key.upper()} {data["safeArea"][key]}')
    for key, value in data['type'].items():
        lines.append(f'#define OP1_UI_TEXT_{key.upper()} {value["nominalHeight"]}')
    for alias, profile in data['typeAliases'].items():
        lines.append(f'#define OP1_UI_TEXT_{alias.upper()} OP1_UI_TEXT_{profile.upper()}')
    for key, value in data['color'].items():
        rgb = ', '.join(str(int(value[i:i+2], 16)) for i in (1, 3, 5))
        lines.append(f'#define OP1_UI_RGBA_{key.upper()} {{ {rgb}, 255 }}')
    lines += ['#endif', '']
    human = (references / 'SPEC.md').read_text()
    human = re.sub(r'\(references/([A-Z]+\.md)\)', r'(\1)', human)
    human = human.replace('(PATTERNS.md)', '(EXAMPLES.md)')
    return {ROOT / 'src/tokens.mjs': js, ROOT / 'include/op1_ui_tokens.h': '\n'.join(lines),
            ROOT / 'tokens/op1-ui.json': json.dumps(data, indent=2) + '\n',
            ROOT.parent / 'design-kit.json': json.dumps(spec, indent=2) + '\n',
            ROOT / 'docs/DESIGN.md': human}

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    stale = []
    for path, content in outputs().items():
        if args.check:
            if not path.exists() or path.read_text() != content: stale.append(str(path.relative_to(ROOT.parent)))
        else: path.write_text(content)
    if stale: parser.exit(1, 'Stale generated tokens: ' + ', '.join(stale) + '\n')
    print('Token outputs match JSON' if args.check else 'Generated JS and C tokens')

if __name__ == '__main__': main()
