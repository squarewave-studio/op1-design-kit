export function normalizeText(value) {
  const result = String(value).toUpperCase();
  for (const c of result) if (!Object.hasOwn(glyphs, c)) throw new RangeError(`Unsupported glyph ${c}; choose a supported label or a licensed font adapter`);
  return result;
}

export function measureText(value, height) {
  const count = normalizeText(value).length;
  return count ? (count * 6.5 - 1.5) * height / 10 : 0;
}

export function textLines(value, x, y, height) {
  return [...normalizeText(value)].flatMap((c, i) => glyphs[c].map(line => line.split(' ').map(pair => {
    const [gx, gy] = pair.split(',').map(Number);
    return [x + (gx + i * 6.5) * height / 10, y + gy * height / 10];
  })));
}
